public class ForLoop {

    public static void main(String[] args){

        // for loop is to run the program in a specific range
        // There are 4 types of loops
        /*
        1. For loop -- you know the range
        2. While loop -- you want to run it forever
        3. Do while loop -- same thing with while loop but different syntax
        4. ForEach loop -- you want to iterate each index
        */

        // variable ; switch/condition ; increment/decrement
        for(int i = 0 ; i < 5 ; i++){
            System.out.println(i+ 1);
        }

    }
    
}
